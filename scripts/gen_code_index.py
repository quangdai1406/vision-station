"""Write docs/CODE_INDEX.md: every Python file and its classes and functions, one line each.

    python3 scripts/gen_code_index.py            # rewrite docs/CODE_INDEX.md
    python3 scripts/gen_code_index.py --check    # exit 1 when the file is stale

Standard library only. Test files list the file and its test classes only.
"""
from __future__ import annotations

import ast
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "CODE_INDEX.md"
DIRS = ("station", "trainer", "tools", "scripts", "tests")
HEADER = (
    "# Code index\n\n"
    "Generated by `python3 scripts/gen_code_index.py`; do not edit by hand. "
    "One line per file, class and top-level function.\n"
)


def _doc_line(node: ast.AST) -> str:
    doc = ast.get_docstring(node) or ""
    return doc.strip().splitlines()[0].strip() if doc.strip() else ""


def _describe(path: pathlib.Path) -> list[str]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError, OSError) as exc:
        return [f"- `{path.relative_to(ROOT).as_posix()}`: unreadable ({type(exc).__name__})"]
    rel = path.relative_to(ROOT).as_posix()
    is_test = rel.startswith("tests/")
    lines = [f"- `{rel}`: {_doc_line(tree)}".rstrip(": ").rstrip()]
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            summary = _doc_line(node)
            if is_test:
                lines.append(f"  - class `{node.name}`")
                continue
            methods = [n.name for n in node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
                       and not n.name.startswith("__")]
            tail = f" (methods: {', '.join(methods)})" if methods else ""
            lines.append(f"  - class `{node.name}`: {summary}{tail}".rstrip(": ").rstrip())
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not is_test:
            lines.append(f"  - def `{node.name}`: {_doc_line(node)}".rstrip(": ").rstrip())
    return lines


def build() -> str:
    out = [HEADER]
    for name in DIRS:
        folder = ROOT / name
        if not folder.is_dir():
            continue
        out.append(f"\n## {name}/\n")
        for path in sorted(folder.rglob("*.py")):
            if "__pycache__" in path.parts:
                continue
            out.extend(_describe(path))
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/CODE_INDEX.md is stale: run python3 scripts/gen_code_index.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
