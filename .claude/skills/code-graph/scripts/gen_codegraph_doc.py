"""Write docs/CODEGRAPH.md from the code graph (standard library only, any repo).

    python3 .claude/skills/code-graph/scripts/gen_codegraph_doc.py          # rebuild + rewrite
    python3 .claude/skills/code-graph/scripts/gen_codegraph_doc.py --check  # exit 1 if stale

The raw graph (.codegraph/graph.json) is never committed; this overview is. Output has no
timestamps, so --check is exact. Blind spots (what static imports cannot show) are read from
.claude/skills/code-graph/blind_spots.txt, one bullet per line; keep them current by hand.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]  # <root>/.claude/skills/code-graph/scripts
CG = HERE / "codegraph.py"
GRAPH = ROOT / ".codegraph" / "graph.json"
OUT = ROOT / "docs" / "CODEGRAPH.md"
BLIND = HERE.parent / "blind_spots.txt"
NOTES_FILE = HERE.parent / "notes.txt"  # optional: extra lines for the 'How to run' section


def build_graph() -> dict:
    subprocess.run([sys.executable, str(CG), "--root", str(ROOT), "build"], check=True,
                   stdout=subprocess.DEVNULL)
    return json.loads(GRAPH.read_text(encoding="utf-8"))


def purpose_of(path: Path) -> str:
    """First docstring line (Python) or first // comment line (JS/TS)."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    if path.suffix == ".py":
        s = text.lstrip()
        if s.startswith(('"""', "'''")):
            lines = s[3:].strip().splitlines()
            return lines[0].strip().rstrip('"').strip() if lines else ""
        return ""
    for line in text.splitlines():
        m = re.match(r"\s*//\s?(.*\S)", line)
        if m:
            return m.group(1).strip()
        if line.strip().startswith(("/**", "/*")):
            inner = line.strip().lstrip("/*").strip()
            if inner:
                return inner.rstrip("*/").strip()
    return ""


def render(graph: dict) -> str:
    files = graph["files"]
    imports_of: dict[str, set[str]] = defaultdict(set)
    imported_by: dict[str, set[str]] = defaultdict(set)
    for e in graph["edges"]:
        if e["kind"] == "import":
            imports_of[e["src"]].add(e["dst"])
            imported_by[e["dst"]].add(e["src"])

    def is_test(p: str) -> bool:
        return bool(files[p].get("is_test"))

    code = sorted(p for p in files if not is_test(p))
    tests = sorted(p for p in files if is_test(p))

    def tests_reaching(p: str) -> list[str]:
        seen, stack, found = {p}, [p], set()
        while stack:
            cur = stack.pop()
            for src in imported_by[cur]:
                if src in seen:
                    continue
                seen.add(src)
                if is_test(src):
                    found.add(src)
                else:
                    stack.append(src)
        return sorted(found)

    out: list[str] = []
    add = out.append
    add("# Code graph overview\n")
    add("Generated by `.claude/skills/code-graph/scripts/gen_codegraph_doc.py`. **Read this first, "
        "then run `CG build` and `CG summary`** before planning or editing. Do not edit by hand; "
        "regenerate it (see below) and commit it with your change. It is static and approximate: it "
        "shows imports, not runtime wiring (see 'What the graph cannot see').\n")
    add("```\nCG = python3 .claude/skills/code-graph/scripts/codegraph.py\n"
        "CG build | CG summary | CG impact <path> | CG symbol <name> | CG tests-for <path> | CG changed\n"
        "python3 .claude/skills/code-graph/scripts/gen_codegraph_doc.py [--check]\n```\n")
    if NOTES_FILE.exists():
        for line in NOTES_FILE.read_text(encoding="utf-8").splitlines():
            if line.strip():
                add(line)
        add("")
    add(f"{len(code)} code files, {len(tests)} test files, "
        f"{sum(len(v) for v in imports_of.values())} import edges.\n")

    add("## Modules\n")
    add("| File | Lines | Imported by | Tests reaching it | Purpose (first docstring/comment line) |")
    add("|---|---:|---:|---:|---|")
    for p in code:
        purpose = purpose_of(ROOT / p).replace("|", "/")
        add(f"| `{p}` | {files[p]['lines']} | {len(imported_by[p])} | {len(tests_reaching(p))} | {purpose} |")
    add("")

    add("## Hubs (change with care)\n")
    for p in sorted(code, key=lambda p: (-len(imported_by[p]), p))[:8]:
        add(f"- `{p}`: imported by {len(imported_by[p])} files")
    add("")

    add("## Internal imports (who imports what)\n")
    for p in code:
        deps = sorted(d for d in imports_of[p] if not is_test(d))
        add(f"- `{p}` -> " + (", ".join(f"`{d}`" for d in deps) if deps else "(no internal imports)"))
    add("")

    add("## Tests and the code they import directly\n")
    for t in tests:
        deps = sorted(d for d in imports_of[t] if not is_test(d))
        add(f"- `{t}` -> " + (", ".join(f"`{d}`" for d in deps) if deps else "(none)"))
    add("")

    skip_names = {"__init__.py"}
    untested = [p for p in code if not tests_reaching(p) and Path(p).name not in skip_names]
    add("## Code with no test reaching it\n")
    add(", ".join(f"`{p}`" for p in untested) if untested else "None.")
    add("")

    ext: dict[str, int] = defaultdict(int)
    for p in code:
        for name in files[p]["external"]:
            ext[name] += 1
    add("## External packages (code files importing each)\n")
    add(", ".join(f"`{k}` ({v})" for k, v in sorted(ext.items(), key=lambda kv: (-kv[1], kv[0]))))
    add("")

    add("## What the graph cannot see\n")
    if BLIND.exists():
        for line in BLIND.read_text(encoding="utf-8").splitlines():
            if line.strip():
                add(f"- {line.strip()}")
    else:
        add("- (no blind_spots.txt: add one next to this script)")
    add("")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    text = render(build_graph())
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/CODEGRAPH.md is out of date: run python3 .claude/skills/code-graph/scripts/gen_codegraph_doc.py")
            return 1
        print("docs/CODEGRAPH.md is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
